function normalizedLanguage(language) {
  if (language === "zh-Hant") return "zh";
  if (language === "zh-Hans") return "zh";
  return language || "ko";
}

function deepTranslate(language, value) {
  if (typeof value === "string") return translate(language, value);
  if (Array.isArray(value)) return value.map((item) => deepTranslate(language, item));
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, deepTranslate(language, item)]));
  return value;
}

export function translate(language, text) {
  const key = normalizedLanguage(language);
  if (!text || key === "ko") return text;
  return copy[key]?.[text] || (key !== "en" ? copy.en?.[text] : null) || text;
}

